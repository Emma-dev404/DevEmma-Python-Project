#Arithmetic Operators - Simple calculations

x = 90
y = 5

print( x + y)
print( x - y)
print( x * y)
print( x / y)
print( x % y) #Modulus - Returns remainder after division

#Comparison Operators - Compare values and return boolean
num1 = 45
num2 = 20

print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2) #Equal to
print(num1 != num2) #Not Equal

#Assignment Operators - Assign/Store values in variables
number = 80
print(number )

#Operator Precedence - BODMAS
number += 2
print(number)

#Logical Operators - and(&&), or( ) , not( )
print( 100==50 and 60 < 80)
print( 100==50 or 60 < 80)
print( not(100==50 and 60 < 80))