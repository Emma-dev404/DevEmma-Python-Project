#while loop

number = 20   #here you assign the first number you want to see(Initialize)

while number <= 25:   #condition
    print(number)
    number += 1    #Increment/Decrement


#For Loop -  avoids repetition like while loop
for x in range(100, 91, -1):      #(starting number, last number, increment/decrement)
    print(x)
